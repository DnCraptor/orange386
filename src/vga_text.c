static void init_attr(void)
{
    if (initialized) return;
    for (unsigned i = 0; i < 16; ++i) attr[i] = (uint8_t)i;
    initialized = 1;
}

void vga_text_io_write(uint16_t port, uint8_t value)
{
    init_attr();
    switch (port) {
    case 0x3d4: crtc_index = value; break;
    case 0x3d5:
        if (crtc_index < sizeof(crtc)) crtc[crtc_index] = value;
        break;
    case 0x3c0:
        if (!attr_flipflop) attr_index = value & 0x1f;
        else if (attr_index < sizeof(attr)) attr[attr_index] = value;
        attr_flipflop ^= 1;
        break;
    }
}

uint8_t vga_text_io_read(uint16_t port)
{
    init_attr();
    switch (port) {
    case 0x3d4: return crtc_index;
    case 0x3d5: return crtc_index < sizeof(crtc) ? crtc[crtc_index] : 0xff;
    case 0x3c1: return attr_index < sizeof(attr) ? attr[attr_index] : 0xff;
    case 0x3da:
        attr_flipflop = 0;
        /* Toggle vertical retrace so BIOS polling loops can progress. */
        { static uint8_t retrace; retrace ^= 8; return retrace | 1; }
    default: return 0xff;
    }
}

void vga_text_render(uint8_t *pixels, uint32_t pitch,
                     uint32_t width, uint32_t height, const uint8_t *ram)
{
    if (!pixels || !ram || width < 720 || height < 400) return;
    init_attr();
    uint32_t x0 = (width - 720) / 2, y0 = (height - 400) / 2;
    uint32_t start = ((uint32_t)crtc[0x0c] << 8 | crtc[0x0d]) & 0x3fff;
    for (uint32_t cy = 0; cy < 25; ++cy) {
        for (uint32_t sy = 0; sy < 16; ++sy) {
            uint32_t *dst = (uint32_t *)(pixels + (y0 + cy * 16 + sy) * pitch) + x0;
            for (uint32_t cx = 0; cx < 80; ++cx) {
                uint32_t cell = (start + cy * 80 + cx) & 0x3fff;
                uint8_t ch = ram[0xb8000 + cell * 2];
                uint8_t a = ram[0xb8000 + cell * 2 + 1];
                uint32_t fg = ega_rgb[a & 15], bg = ega_rgb[(a >> 4) & 7];
                uint8_t bits = font8x16[ch][sy];
                for (unsigned x = 0; x < 8; ++x)
                    dst[cx * 9 + x] = bits & (0x80u >> x) ? fg : bg;
                dst[cx * 9 + 8] = (ch >= 0xc0 && ch <= 0xdf && (bits & 1)) ? fg : bg;
            }
        }
    }
}
